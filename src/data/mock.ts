/** Deterministic pseudo-random activity intensity (0-4) for the study heatmap. */
export function heatmapIntensity(week: number, day: number): number {
  const seed = Math.sin(week * 7.13 + day * 3.71) * 10000;
  const value = seed - Math.floor(seed);
  if (value < 0.25) return 0;
  if (value < 0.45) return 1;
  if (value < 0.65) return 2;
  if (value < 0.85) return 3;
  return 4;
}
